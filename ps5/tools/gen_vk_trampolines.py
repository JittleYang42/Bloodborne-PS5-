#!/usr/bin/env python3
"""bbport PS5: Vulkan's global commands for code that calls them directly (FSR, parts of
shadPS4), on the RADV linked into the title.

Mesa's RADV archive exports only its ICD entry (vk_icdGetInstanceProcAddr); a PC links the
Vulkan loader for vkCreateImage and the rest. This writes one trampoline per command declared in
vulkan_core.h: the first call resolves it through vkGetInstanceProcAddr with the instance the
title created (device commands too: Mesa's instance-level lookup returns dispatching entries),
and each later call goes straight to it. vkGetInstanceProcAddr is ours as well, so the
instance vulkan.hpp creates is recorded too.

    gen_vk_trampolines.py vulkan_core.h out.c
"""
import re
import sys

source = open(sys.argv[1], encoding='utf-8').read()
# Prototypes sit under #ifndef VK_NO_PROTOTYPES, one per command:
#   VKAPI_ATTR VkResult VKAPI_CALL vkCreateInstance(
#       const VkInstanceCreateInfo* pCreateInfo, ...);
pattern = re.compile(r'VKAPI_ATTR\s+([\w\s\*]+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\)\s*;', re.S)
special = {'vkGetInstanceProcAddr', 'vkCreateInstance', 'vkDestroyInstance'}
seen = set()
out = ['/* Generated by ps5/tools/gen_vk_trampolines.py: do not edit. */',
       '#include <stdatomic.h>',
       '#include <string.h>',
       '#include <vulkan/vulkan_core.h>',
       '',
       'VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vk_icdGetInstanceProcAddr(VkInstance instance, const char *name);',
       'static _Atomic(VkInstance) bb_instance;',
       'static PFN_vkVoidFunction bb_resolve(const char *name) {',
       '    PFN_vkVoidFunction f = vk_icdGetInstanceProcAddr(atomic_load(&bb_instance), name);',
       '    return f ? f : vk_icdGetInstanceProcAddr(NULL, name);',
       '}',
       'static VKAPI_ATTR VkResult VKAPI_CALL bb_create_instance(const VkInstanceCreateInfo *info,',
       '        const VkAllocationCallbacks *allocator, VkInstance *instance) {',
       '    PFN_vkCreateInstance create = (PFN_vkCreateInstance)vk_icdGetInstanceProcAddr(NULL, "vkCreateInstance");',
       '    VkResult result = create(info, allocator, instance);',
       '    if (result == VK_SUCCESS) atomic_store(&bb_instance, *instance);',
       '    return result;',
       '}',
       'static VKAPI_ATTR void VKAPI_CALL bb_destroy_instance(VkInstance instance, const VkAllocationCallbacks *allocator) {',
       '    PFN_vkDestroyInstance destroy = (PFN_vkDestroyInstance)vk_icdGetInstanceProcAddr(instance, "vkDestroyInstance");',
       '    VkInstance expected = instance;',
       '    atomic_compare_exchange_strong(&bb_instance, &expected, (VkInstance)VK_NULL_HANDLE);',
       '    if (destroy) destroy(instance, allocator);',
       '}',
       'VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vkGetInstanceProcAddr(VkInstance instance, const char *name) {',
       '    if (!strcmp(name, "vkGetInstanceProcAddr")) return (PFN_vkVoidFunction)vkGetInstanceProcAddr;',
       '    if (!strcmp(name, "vkCreateInstance")) return (PFN_vkVoidFunction)bb_create_instance;',
       '    if (!strcmp(name, "vkDestroyInstance")) return (PFN_vkVoidFunction)bb_destroy_instance;',
       '    if (instance) atomic_store(&bb_instance, instance);',
       '    return vk_icdGetInstanceProcAddr(instance, name);',
       '}',
       'VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL bb_ps5_vkGetInstanceProcAddr(VkInstance instance, const char *name) {',
       '    return vkGetInstanceProcAddr(instance, name);',
       '}',
       'VKAPI_ATTR VkResult VKAPI_CALL vkCreateInstance(const VkInstanceCreateInfo *info,',
       '        const VkAllocationCallbacks *allocator, VkInstance *instance) {',
       '    return bb_create_instance(info, allocator, instance);',
       '}',
       'VKAPI_ATTR void VKAPI_CALL vkDestroyInstance(VkInstance instance, const VkAllocationCallbacks *allocator) {',
       '    bb_destroy_instance(instance, allocator);',
       '}',
       '']
count = 0
for ret, name, params in pattern.findall(source):
    if name in seen or name in special:
        continue
    seen.add(name)
    ret = ' '.join(ret.split())
    params = ' '.join(params.split())
    if params in ('', 'void'):
        names = []
    else:
        names = []
        for p in params.split(','):
            p = p.strip()
            m = re.search(r'(\w+)\s*(\[[^\]]*\])?$', p)
            names.append(m.group(1))
    call = ', '.join(names)
    out.append(f'static PFN_{name} p_{name};')
    out.append(f'VKAPI_ATTR {ret} VKAPI_CALL {name}({params if params else "void"}) {{')
    out.append(f'    if (!p_{name}) p_{name} = (PFN_{name})bb_resolve("{name}");')
    if ret == 'void':
        out.append(f'    p_{name}({call});')
    else:
        out.append(f'    return p_{name}({call});')
    out.append('}')
    count += 1
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'{count} Vulkan trampolines')
